#!/usr/bin/env python3
"""design_system.py: the ux-design-system skill. Points a project at a design system or authors a subset of one.

Modes:
    point SPEC [--docs DOCS]        Pin a published design system (`@scope/name@1.2.3`, an exact version) or a
                                    local folder in DOCS/ux/package.json, after validating it through the kit
                                    resolver; prints the Dependabot entry to add.
    subset SRC                      Read a DESIGN.md (a Google DESIGN.md: YAML front matter and prose), write
                                    SRC's folder design-system/ (one CSS file per filled module,
                                    kit-manifest.json, the prose as guidance.md), validate it through the
                                    resolver, and pin it when the project has no pin yet. Without chart colours,
                                    writes a proposed palette into SRC's `colors` and stops; generation refuses
                                    while the top-level `proposed:` mark remains.
    subset --from-legacy TOKENS     Turn a legacy docs/ux/tokens.css (or docs/design/tokens.css) into a draft
                                    docs/ux/DESIGN.md: core from the file, proposed chart colours.
    scaffold [DOCS]                 Create DOCS/ux/DESIGN.md (default DOCS=docs) from the template.

`generate` and its `refresh` alias were removed in delivery-comms 2.0.0; running either prints the `subset`
command that replaces it. Refusals exit 2. Python 3.12+, PyYAML.
"""
