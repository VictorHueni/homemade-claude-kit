# DESIGN.md is a Google DESIGN.md (github.com/google-labs-code/design.md, docs/spec.md, format "alpha"): the
# top-level keys below, colour and typography token names free-form, a typography token an object of the
# properties below. Each contract role the kit reads has one place in it, (group, token, typography property):
# colours and the rounded and spacing roles under their contract name without the leading dashes, the font
# roles as properties of the typography tokens body, heading, mono and text-*, and the roles Google has no key
# for under the `kit` extension key, whose values the Google linter does not take for tokens.
GOOGLE_KEYS = ("version", "name", "description", "omitted", "colors", "typography", "rounded", "spacing",
               "components")
TYPOGRAPHY_PROPS = ("fontFamily", "fontSize", "fontWeight", "lineHeight", "letterSpacing", "fontFeature",
                    "fontVariation")
COLOR_ROLES = ("ink", "muted", "canvas-bg", "surface", "surface-2", "border", "accent", "accent-ink", "success",
               "warning", "danger", "info", "chart-1", "chart-2", "chart-3", "chart-4", "chart-rest",
               "chart-axis", "chart-grid", "chart-highlight")
TYPOGRAPHY_ROLES = {
    "--font-body": ("body", "fontFamily"), "--font-size-md": ("body", "fontSize"),
    "--line-height-body": ("body", "lineHeight"), "--font-weight-regular": ("body", "fontWeight"),
    "--font-heading": ("heading", "fontFamily"), "--title-size": ("heading", "fontSize"),
    "--line-height-tight": ("heading", "lineHeight"), "--font-weight-bold": ("heading", "fontWeight"),
    "--font-mono": ("mono", "fontFamily"),
    "--font-size-xs": ("text-xs", "fontSize"), "--font-size-sm": ("text-sm", "fontSize"),
    "--font-size-lg": ("text-lg", "fontSize"), "--font-size-xl": ("text-xl", "fontSize"),
}
ROUNDED_ROLES = ("card-radius", "btn-radius", "node-radius", "radius-sm", "radius-pill")
SPACING_ROLES = ("space-sm", "space-md", "space-lg", "shell-max", "space-xs", "space-xl")
KIT_ROLES = ("shadow", "border-width")
PLACES = {**{"--" + n: ("colors", n, None) for n in COLOR_ROLES},
          **{role: ("typography", token, prop) for role, (token, prop) in TYPOGRAPHY_ROLES.items()},
          **{"--" + n: ("rounded", n, None) for n in ROUNDED_ROLES},
          **{"--" + n: ("spacing", n, None) for n in SPACING_ROLES},
          **{"--" + n: ("kit", n, None) for n in KIT_ROLES}}
PROPOSED = "proposed"
KIT_KEYS = (*KIT_ROLES, "fonts", "omitted")
FONT_KEYS = ("family", "src", "weight", "style")
FONT_FORMATS = {".woff2": "woff2", ".woff": "woff", ".ttf": "truetype", ".otf": "opentype"}
# The artefact front matter every kit document may carry (metamodel artefact-frontmatter); ignored here.
ARTEFACT_KEYS = ("type", "title", "description", "tags", "timestamp", "status", "owner", "last_reviewed",
                 "review_interval")
# The top-level keys the kit reads: an unknown key this close to one of them is a typo, not an extension.
KIT_USED = ("name", "colors", "typography", "rounded", "spacing", "kit", PROPOSED)
# Google keys the kit does not read, noted when present.
GOOGLE_UNUSED = ("version", "description", "omitted", "components")
MOVED = {"dataviz": "the chart colours go under `colors` (chart-1 to chart-4, chart-rest, chart-axis, "
                    "chart-grid, chart-highlight)",
         "elevation": "`shadow` goes under `kit` (kit.shadow)",
         "fonts": "font faces go under `kit` (kit.fonts)"}
PRIMARY_ALIAS = "{colors.accent}"
UNSAFE = re.compile(r"[;{}<>]|/\*|\*/")
HEX = re.compile(r"#(?:[0-9a-fA-F]{3}|[0-9a-fA-F]{6})")


def fail(message):
    raise DesignError(message)


def rel(path):
    """`path` relative to the working directory when it lies below it, else as given."""
    try:
        return Path(path).resolve().relative_to(Path.cwd().resolve()).as_posix()
    except ValueError:
        return str(path)


def write_text(path, text):
    """Write `path` atomically (a temporary file renamed into place)."""
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(prefix=f".{path.name}.", dir=path.parent)
    with os.fdopen(fd, "w", encoding="utf-8") as handle:
        handle.write(text)
    os.replace(tmp, path)


def slug(text):
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-") or "project"


# --- DESIGN.md ------------------------------------------------------------------------------------

def split_front_matter(text, src):
    """(front matter YAML, body after it, the match of the whole `---` block)."""
    match = re.match(r"---[ \t]*\n(.*?\n)?---[ \t]*(?:\n|$)", text, re.S)
    if not match:
        fail(f"{src} has no YAML front matter (a `---` block at the top of the file)")
    return match.group(1) or "", text[match.end():], match


def load_front_matter(text, src):
    raw, body, _ = split_front_matter(text, src)
    try:
        data = yaml.safe_load(raw)
    except yaml.YAMLError as exc:
        fail(f"{src}: the front matter is not plain YAML ({exc.__class__.__name__}: {exc})")
    if data is None:
        data = {}
    if not isinstance(data, dict):
        fail(f"{src}: the front matter must be a mapping of keys")
    return data, body


def check_keys(where, keys, allowed):
    unknown = [k for k in keys if k not in allowed]
    if unknown:
        fail(f"{where}: unknown key(s) {', '.join(map(str, unknown))}; allowed: {', '.join(allowed)}")


def distance(a, b):
    """Levenshtein distance (the measure the Google linter uses to tell a typo from an extension key)."""
    row = list(range(len(b) + 1))
    for i, ca in enumerate(a, start=1):
        prev, row[0] = row[0], i
        for j, cb in enumerate(b, start=1):
            prev, row[j] = row[j], min(row[j] + 1, row[j - 1] + 1, prev + (ca != cb))
    return row[-1]


def near(word, candidates, limit=2):
    """The closest candidate within `limit` edits of `word`, else None."""
    best = min(candidates, key=lambda c: distance(word.lower(), c.lower()), default=None)
    return best if best is not None and distance(word.lower(), best.lower()) <= limit else None


def css_value(where, value):
    if isinstance(value, bool) or not isinstance(value, (str, int, float)):
        fail(f"{where}: give a CSS value as a string or a number (got {value!r})")
    text = str(value).strip()
    if not text or UNSAFE.search(text):
        fail(f"{where}: {text!r} is not a single CSS value (empty, or holds ; {{ }} < > or a comment)")
    return text


def path_of(role):
    """Where `role` is written in a DESIGN.md, such as colors.accent or typography.body.fontFamily."""
    return ".".join(part for part in PLACES[role] if part)


def mapping(src, where, block):
    if block is None:
        return {}
    if not isinstance(block, dict):
        fail(f"{src}: `{where}` must be a mapping")
    return block


def missing_message(src, module, missing, found, skipped, colors):
    """The roles of `module` the DESIGN.md lacks, each with its path and a hint when one is at hand."""
    lines = []
    for role in missing:
        group, token, _ = PLACES[role]
        line = path_of(role) + f" ({role})"
        typo = near(f"{group}.{token}", [s for s in skipped if s.startswith(group + ".")])
        if typo:
            line += f", found `{typo}`: a typo?"
        primary = colors.get("primary")
        if role == "--accent" and isinstance(primary, str) and HEX.fullmatch(primary.strip()):
            line += (f"; Google's `primary` is the kit's accent: add `accent: {json.dumps(primary.strip())}` "
                     "under colors")
        lines.append(line)
    if module == "core":
        head = f"{src}: the `core` roles are required"
        if found:
            head = f"{src}: the `core` module is filled in part; give every role"
    else:
        head = f"{src}: the `{module}` module is filled in part; give every role or none"
    return head + ". Missing: " + "; ".join(lines)


def parse(src):
    """{module: {role: value}}, the omitted map, font faces, the prose body, whether a proposal is open, and
    the keys and tokens the kit skipped."""
    data, body = load_front_matter(Path(src).read_text(encoding="utf-8"), src)
    skipped = []
    for key in data:
        key = str(key)
        if key in MOVED:
            fail(f"{src}: `{key}` is not a DESIGN.md key (the kit's DESIGN.md is a Google DESIGN.md): {MOVED[key]}")
        if key in GOOGLE_UNUSED:
            skipped.append(key)
        elif key not in (*GOOGLE_KEYS, *ARTEFACT_KEYS, "kit", PROPOSED):
            typo = near(key, KIT_USED)
            if typo:
                fail(f"{src}: unknown key `{key}`; did you mean `{typo}`?")
            skipped.append(key)
    if isinstance(data.get("omitted"), dict):
        fail(f"{src}: Google's `omitted` lists DESIGN.md sections; the modules the design leaves out, with "
             "the reason, go under `kit.omitted`")

    contract = design_source._contract()
    module_of = {role: module for module, spec in contract["modules"].items() for role in spec["roles"]}
    colors = mapping(src, "colors", data.get("colors"))
    kit = mapping(src, "kit", data.get("kit"))
    for key in kit:
        if key not in KIT_KEYS:
            hint = near(str(key), KIT_KEYS)
            fail(f"{src}: unknown key `kit.{key}`" + (f"; did you mean `kit.{hint}`?" if hint else "")
                 + f" Allowed under kit: {', '.join(KIT_KEYS)}")
    found = {}
    for group in ("colors", "rounded", "spacing", "kit"):
        block = colors if group == "colors" else kit if group == "kit" else mapping(src, group, data.get(group))
        for name, value in block.items():
            name = str(name)
            if group == "kit" and name in ("fonts", "omitted"):
                continue
            if "--" + name in PLACES and PLACES["--" + name][0] == group:
                found["--" + name] = (f"{group}.{name}", value)
            elif not (group == "colors" and name == "primary" and value == PRIMARY_ALIAS):
                skipped.append(f"{group}.{name}")
    entries = {token for token, _ in TYPOGRAPHY_ROLES.values()}
    roles_of = {(token, prop): role for role, (token, prop) in TYPOGRAPHY_ROLES.items()}
    for token, entry in mapping(src, "typography", data.get("typography")).items():
        token = str(token)
        if token not in entries:
            skipped.append(f"typography.{token}")
            continue
        if not isinstance(entry, dict):
            fail(f"{src} `typography.{token}`: a typography token is an object of "
                 f"{', '.join(TYPOGRAPHY_PROPS)} (got {entry!r}), such as `{token}: {{fontFamily: ...}}`")
        for prop, value in entry.items():
            prop = str(prop)
            if prop not in TYPOGRAPHY_PROPS:
                hint = near(prop, TYPOGRAPHY_PROPS)
                fail(f"{src} `typography.{token}.{prop}`: not a typography property"
                     + (f"; did you mean `{hint}`?" if hint else "") + f" Allowed: {', '.join(TYPOGRAPHY_PROPS)}")
            if (token, prop) in roles_of:
                found[roles_of[(token, prop)]] = (f"typography.{token}.{prop}", value)
            else:
                skipped.append(f"typography.{token}.{prop}")

    values = {}
    for role, (where, value) in found.items():
        text = css_value(f"{src} `{where}`", value)
        if where.startswith("colors.") and not HEX.fullmatch(text):
            fail(f"{src} `{where}`: {text!r} is not a hex colour (#rgb or #rrggbb); colours are hex so their "
                 "contrast can be checked")
        values.setdefault(module_of[role], {})[role] = text
    for module in [m for m in contract["modules"] if m in values or m == "core"]:
        missing = [r for r in contract["modules"][module]["roles"] if r not in values.get(module, {})]
        if missing:
            fail(missing_message(src, module, missing, values.get(module), skipped, colors))

    omitted = mapping(src, "kit.omitted", kit.get("omitted"))
    optional = [m for m, spec in contract["modules"].items() if not spec["required"]]
    check_keys(f"{src} `kit.omitted`", list(omitted), optional)
    for module, reason in omitted.items():
        if not isinstance(reason, str) or not reason.strip():
            fail(f"{src} `kit.omitted.{module}`: give the reason as text")
        if module in values:
            fail(f"{src}: `{module}` is both filled and listed in `kit.omitted`; keep one")
    if "dataviz" in values and "dataviz" in omitted:
        fail(f"{src}: `dataviz` is required and cannot be omitted")

    fonts = kit.get("fonts") or []
    if not isinstance(fonts, list):
        fail(f"{src}: `kit.fonts` is a list of font faces (family, src, weight, style)")
    for index, face in enumerate(fonts):
        where = f"{src} `kit.fonts[{index}]`"
        if not isinstance(face, dict):
            fail(f"{where}: a font face is a mapping (family, src, weight, style)")
        check_keys(where, list(face), FONT_KEYS)
        for key in ("family", "src"):
            if key not in face:
                fail(f"{where}: `{key}` is required")
        source = str(face["src"])
        if re.match(r"[a-z][a-z0-9+.-]*:", source, re.I) or source.startswith("//"):
            fail(f"{where}: `src` {source!r} must be a font file beside the DESIGN.md; the kit loads no font "
                 "from the network")
        for key in ("family", "weight", "style"):
            if key in face:
                css_value(f"{where}.{key}", face[key])
    return {"values": values, "omitted": omitted, "fonts": fonts, "body": body, "proposed": PROPOSED in data,
            "skipped": skipped, "name": str(data.get("name") or data.get("title") or "")}


# --- the proposed dataviz palette -----------------------------------------------------------------

STEPS = (0.0, 0.25, 0.5, 0.75)


def _rgb(hex_colour):
    h = hex_colour.lstrip("#")
    if len(h) == 3:
        h = "".join(c * 2 for c in h)
    return [int(h[i: i + 2], 16) for i in (0, 2, 4)]


def mix(a, b, t):
    """`a` moved a fraction `t` of the way towards `b`, in sRGB."""
    return "#" + "".join(f"{round(x + (y - x) * t):02x}" for x, y in zip(_rgb(a), _rgb(b)))


def propose_dataviz(core):
    """The eight dataviz roles from the core colours, contrast-checked against the contract pairs.

    --chart-1 to --chart-4: four steps from --accent towards --surface (0, 25, 50 and 75 per cent), darkest
    first; a step whose text pair fails moves further towards the surface until --accent-ink or --ink reaches
    AA on it. --chart-rest (the remainder fill): --muted halfway towards --surface. --chart-axis: --muted.
    --chart-grid: --border. --chart-highlight: --warning.
    """
    accent, surface = core["--accent"], core["--surface"]
    pairs = {p["bg"]: p for p in design_source._contract()["pairs"]}
    roles, floor = {}, 0.0
    for index, target in enumerate(STEPS, start=1):
        role = f"--chart-{index}"
        t = max(target, floor)
        colour = mix(accent, surface, t)
        pair = pairs.get(role)
        while pair and t < 1.0:
            tried = design_source.pair_ratios({**core, role: colour}, pair) or []
            if any(ratio >= design_source.AA for _, ratio in tried):
                break
            t = min(1.0, t + 0.01)
            colour = mix(accent, surface, t)
        roles[role], floor = colour, t + 0.1
    roles["--chart-rest"] = mix(core["--muted"], surface, 0.5)
    roles["--chart-axis"] = core["--muted"].lower()
    roles["--chart-grid"] = core["--border"].lower()
    roles["--chart-highlight"] = core["--warning"].lower()
    return roles


def insert_proposal(src, core):
    """Write the proposed chart colours at the end of the `colors` block of `src`, followed by the top-level
    `proposed:` mark listing them; the rest of the file, comments included, is kept as it is."""
    text = Path(src).read_text(encoding="utf-8")
    _, _, match = split_front_matter(text, src)
    lines = text[: match.end()].splitlines(keepends=True)
    start = next((i for i, line in enumerate(lines) if re.match(r"colors:[ \t]*(#.*)?$", line.rstrip("\n"))), None)
    if start is None:
        fail(f"{rel(src)}: write `colors` as a block mapping (one colour per line) so the proposal can be added")
    end = start + 1
    while end < len(lines) - 1 and (not lines[end].strip() or lines[end][0] in " \t"):
        end += 1
    while end > start + 1 and not lines[end - 1].strip():
        end -= 1
    children = [line for line in lines[start + 1: end] if line.strip() and not line.lstrip().startswith("#")]
    indent = re.match(r"[ \t]*", children[0]).group(0) if children else "  "
    roles = propose_dataviz(core)
    block = [
        "# Proposed by ux-design-system subset: a starting chart palette for you to review.",
        f"# chart-1 to chart-4 are four steps from accent {core['--accent']} towards surface {core['--surface']},",
        "# darkest first, each with text that reaches WCAG AA; chart-rest (the remainder fill) is muted halfway",
        "# to the surface; chart-axis is muted, chart-grid is border, chart-highlight is warning.",
    ]
    block = [indent + line for line in block] + [f'{indent}{role[2:]}: "{value}"' for role, value in roles.items()]
    block += ["# Change any chart colour you like, then delete the `proposed:` line below; subset refuses while "
              "it remains.",
              f"{PROPOSED}: [{', '.join(role[2:] for role in roles)}]"]
    head = "".join(lines[:end]) + "".join(line + "\n" for line in block) + "".join(lines[end:])
    write_text(Path(src), head + text[match.end():])


